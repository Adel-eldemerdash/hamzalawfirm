/**
 * The result page.
 *
 * Section order follows 01-TOOL-SPEC.md section 6.1. Layers 1 and 4 — the
 * legal characterization and the gap map — carry the visual weight, because
 * the PDPC portal already answers layers 2 and 3 and those two are where the
 * firm's work shows.
 */

import { Result } from "./rules";
import { Answers } from "./flow";
import { QUESTIONS_BY_ID } from "./questions";
import { Item } from "./content";
import { t } from "./i18n";
import {
  roleItem, primaryItem, suppItem, regItem, docItem, noticeItem,
  roleQualifier, primaryExclusivity, supplementaryPrerequisite,
  feeCeilings, timelines, disclaimerParagraphs, exemptNote, feeFor, qText,
} from "./resolve";

export function disclaimerHtml(): string {
  return (
    '<div class="pdpl__disclaimerbox"><p class="pdpl__label">' + t("labelDisclaimer") + "</p>" +
    disclaimerParagraphs().map(function (p) { return "<p>" + p + "</p>"; }).join("") +
    "</div>"
  );
}

/**
 * Article citations are deliberately absent from the result. The client's
 * instruction of September 9, 2026 is that no legal article is quoted to the
 * visitor; the sources stay in content.ts, which remains the record.
 *
 * `titleOnly` renders the heading with no description, used for the
 * supplementary, registration, and document lists.
 */
function card(item: Item, extraClass?: string, titleOnly?: boolean): string {
  return (
    '<article class="pdpl__card' + (extraClass ? " " + extraClass : "") + '">' +
    "<h3>" + item.title + "</h3>" +
    (!titleOnly && item.body ? "<p>" + item.body + "</p>" : "") +
    "</article>"
  );
}

/** Route a notice to the section it belongs under, by its rule prefix. */
function noticesFor(codes: string[], prefixes: string[]): string[] {
  return codes.filter(function (c) {
    return prefixes.some(function (p) { return c.indexOf(p) === 0; });
  });
}

function noticeBlock(codes: string[], heading: string): string {
  const items = codes
    .map(function (c) { return noticeItem(c); })
    .filter(function (i) { return !!i; }) as Item[];
  if (!items.length) return "";
  return (
    '<div class="pdpl__notices"><p class="pdpl__noticesheading">' + heading + "</p>" +
    items.map(function (i) {
      return (
        '<div class="pdpl__notice"><strong>' + i.title + "</strong>" +
        (i.body ? "<p>" + i.body + "</p>" : "") +
        "</div>"
      );
    }).join("") +
    "</div>"
  );
}

function list(
  codes: string[],
  lookup: (c: string) => Item | undefined,
  cls?: string,
  titleOnly?: boolean
): string {
  const items = codes.map(lookup).filter(function (i) { return !!i; }) as Item[];
  if (!items.length) return "";
  return (
    '<div class="pdpl__cards">' +
    items.map(function (i) { return card(i, cls, titleOnly); }).join("") +
    "</div>"
  );
}

export interface Contact {
  company: string;
  fullName: string;
  email: string;
  phone: string;
}

/**
 * A consultation request that is complete when it opens.
 *
 * Everything the firm needs to respond is already in the body — who is
 * writing, for which company, how to reach them, and what the assessment
 * concluded — so the visitor only has to press send. Asking someone to retype
 * details they entered two screens ago is where these requests get abandoned.
 */
function consultationMailto(r: Result, contact: Contact): string {
  const role = roleItem(r.role);
  const primary = primaryItem(r.primary);

  const lines = [
    "I would like to book a consultation about my PDPL assessment result.",
    "",
    "Please suggest a suitable time. I am available at the number below.",
    "",
    "---",
    "Company: " + contact.company,
    "Name and title: " + contact.fullName,
    "Email: " + contact.email,
    "Phone: " + contact.phone,
    "",
    "Assessment summary",
    "Role: " + (role ? role.title : r.role),
    "Primary instrument: " + (primary ? primary.title : r.primary),
    "Supplementary: " + (r.supplementary.length ? r.supplementary.join(", ") : "none"),
    "Registrations: " + (r.registrations.length ? r.registrations.join(", ") : "none"),
    "Documents identified: " + r.documents.length,
    "Items needing examination: " + (r.unresolved.length ? r.unresolved.join(", ") : "none"),
    "",
    "Generated by the self-assessment tool at hamzalawfirm.com/pdpl-checklist",
  ];

  return (
    "mailto:info@hamzalawfirm.com" +
    "?subject=" + encodeURIComponent("Consultation request - PDPL assessment - " + contact.company) +
    "&body=" + encodeURIComponent(lines.join("\n"))
  );
}

export function renderResult(
  root: HTMLElement,
  r: Result,
  answers: Answers,
  contact: Contact
): string {
  const band = (typeof answers["Q3.1"] === "string" ? answers["Q3.1"] : "") as string;
  const q32 = (typeof answers["Q3.2"] === "string" ? answers["Q3.2"] : "") as string;
  const fee = feeFor(r.primary, band, q32);
  const role = roleItem(r.role);
  const primary = primaryItem(r.primary);

  let html = '<h1 class="pdpl__title">' + t("resultTitle") + "</h1>";

  // 1 — role
  html +=
    '<section class="pdpl__section pdpl__section--feature">' +
    '<h2 class="pdpl__h2">' + t("sec1") + "</h2>" +
    '<p class="pdpl__headline">' + (r.roleQualified ? roleQualifier() : (role ? role.title : "")) + "</p>" +
    (role && role.body ? "<p>" + role.body + "</p>" : "") +
    "</section>";

  // 2 — primary instrument
  if (primary) {
    html +=
      '<section class="pdpl__section">' +
      '<h2 class="pdpl__h2">' + t("sec2") + "</h2>" +
      (r.primaryHedged ? '<p class="pdpl__hedge">' + t("hedge") + "</p>" : "") +
      '<p class="pdpl__headline">' + primary.title + "</p>" +
      "<p>" + primary.body + "</p>" +
      '<div class="pdpl__fee' + (fee.unresolved ? " pdpl__fee--unresolved" : "") + '">' +
      '<p class="pdpl__label">' + t("labelFee") + "</p><p>" + fee.amount + "</p>" +
      (fee.qualifier ? '<p class="pdpl__hedge">' + fee.qualifier + "</p>" : "") +
      (band === "b1" && r.primary.indexOf("BAS-L") === 0
        ? "<p>" + exemptNote() + "</p>"
        : "") +
      "</div>" +
      '<p class="pdpl__source">' + primaryExclusivity() + "</p>" +
      noticeBlock(noticesFor(r.notices, ["B", "N3", "N6a"]).filter(function (c) { return c !== "B7"; }), t("notesOnResult")) +
      "</section>";
  }

  // 3 — supplementary
  if (r.supplementary.length) {
    html +=
      '<section class="pdpl__section">' +
      '<h2 class="pdpl__h2">' + t("sec3") + "</h2>" +
      list(r.supplementary, suppItem, undefined, true) +
      "</section>";
  }

  // 4 — registrations
  if (r.registrations.length) {
    html +=
      '<section class="pdpl__section">' +
      '<h2 class="pdpl__h2">' + t("sec4") + "</h2>" +
      list(r.registrations, regItem, undefined, true) +
      "</section>";
  }

  // 5 — document and obligation map
  html +=
    '<section class="pdpl__section pdpl__section--feature">' +
    '<h2 class="pdpl__h2">' + t("sec5") + "</h2>" +
    '<p class="pdpl__label">' + t("labelRequired") + "</p>" +
    (r.documents.length ? list(r.documents, docItem, undefined, true) : "<p>" + t("nothingFurther") + "</p>");

  if (r.alreadyInPlace.length) {
    html +=
      '<p class="pdpl__label">' + t("labelInPlace") + "</p>" +
      '<p class="pdpl__source">' + t("inPlaceNote") + "</p>" +
      list(r.alreadyInPlace, docItem, "pdpl__card--done", true);
  }

  html += "</section>";

  // 6 — unresolved
  if (r.unresolved.length) {
    html +=
      '<section class="pdpl__section pdpl__section--unresolved">' +
      '<h2 class="pdpl__h2">' + t("sec6") + "</h2>" +
      "<p>" + t("unresolvedLede") + "</p>" +
      "<ul class=\"pdpl__list\">" +
      r.unresolved.map(function (id) {
        const q = QUESTIONS_BY_ID[id];
        return "<li><strong>" + id + "</strong> - " + (q ? qText(q) : "") + "</li>";
      }).join("") +
      "</ul></section>";
  }

  // 7 — timeline
  html +=
    '<section class="pdpl__section">' +
    '<h2 class="pdpl__h2">' + t("sec7") + "</h2>" +
    '<div class="pdpl__tablewrap"><table class="pdpl__table">' +
    "<thead><tr><th>" + t("colItem") + "</th><th>" + t("colPeriod") + "</th></tr></thead><tbody>" +
    timelines().map(function (row) {
      return "<tr><td>" + row.label + "</td><td>" + row.period + "</td></tr>";
    }).join("") +
    "</tbody></table></div></section>";

  // 8 — call to action
  html +=
    '<section class="pdpl__section pdpl__section--cta">' +
    '<h2 class="pdpl__h2">' + t("ctaHeading") + "</h2>" +
    "<p>" + t("ctaBody") + "</p>" +
    '<p><a class="pdpl__btn pdpl__btn--primary" href="' + consultationMailto(r, contact) + '">' + t("ctaButton") + "</a></p>" +
    '<p class="pdpl__ctanote">' + t("ctaNote") + "</p>" +
    '<p class="pdpl__source">' + t("firmLine") + "</p>" +
    "</section>";

  // 9 — disclaimer, always visible and never behind a toggle
  html += disclaimerHtml();

  root.innerHTML = html;
  return html;
}
